export interface AdviceItem {
  field: Field;
  grade: Grade;
  text: string;
}

/**
 * 最後に受けた級の結果から、表示するアドバイスを選ぶ。
 * - 満点でなかった分野を、点数の低い順に（同点なら分野の順）
 * - 全分野が満点なら空（結果画面で別のメッセージを出す）
 */
export function pickAdvice(last: GradeResult | undefined): AdviceItem[] {
  if (!last) return [];
  return FIELDS.filter((f) => last.byField[f] < RULES.questionsPerField)
    .sort((a, b) => last.byField[a] - last.byField[b] || FIELDS.indexOf(a) - FIELDS.indexOf(b))
    .map((f) => ({ field: f, grade: last.grade, text: ADVICE[f][last.grade] }));
}
